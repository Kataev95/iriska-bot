"""Arcade challenges. Server-owned scores, no currency, no client timestamps."""
from secrets import randbelow, choice

GAMES = {
    "catch": {"name":"Ловец сокровищ","icon":"🍎","description":"Лови падающие предметы в нужной дорожке. 5 раундов."},
    "memory": {"name":"Память","icon":"🧠","description":"Запомни 6 символов и повтори последовательность."},
    "maze": {"name":"Лабиринт","icon":"🧭","description":"Найди выход из случайного лабиринта за минимум ходов."},
    "reaction": {"name":"Реакция","icon":"⚡","description":"Нажимай, когда загорится сигнал. 3 раунда."},
}
DAILY_ATTEMPTS = 4
DAILY_REWARDS = 3
REWARD_XP = 20
REWARD_SCORE = 60
SESSION_SECONDS = 120
SYMBOLS = ("🍎","🍀","⭐","💎")
DIRECTIONS = {"up":(-1,0),"down":(1,0),"left":(0,-1),"right":(0,1)}
MAZE_SIZE = 7
MAX_MOVES = 48


def maze_generate():
    # A perfect 7x7 maze with nine rooms, generated by randomized DFS.
    grid = [["#"]*MAZE_SIZE for _ in range(MAZE_SIZE)]
    grid[1][1] = "."
    stack = [(1,1)]
    while stack:
        r,c = stack[-1]
        options = [(r+2*dr,c+2*dc) for dr,dc in DIRECTIONS.values()
                   if 0<r+2*dr<6 and 0<c+2*dc<6 and grid[r+2*dr][c+2*dc]=="#"]
        if not options:
            stack.pop()
            continue
        nr,nc = choice(options)
        grid[(r+nr)//2][(c+nc)//2] = "."
        grid[nr][nc] = "."
        stack.append((nr,nc))
    return ["".join(row) for row in grid]


def shortest_path(grid):
    queue = [(1,1,0)]
    visited = {(1,1)}
    for r,c,d in queue:
        if (r,c)==(5,5):
            return d
        for dr,dc in DIRECTIONS.values():
            nr,nc = r+dr,c+dc
            if 0<=nr<7 and 0<=nc<7 and grid[nr][nc]=="." and (nr,nc) not in visited:
                visited.add((nr,nc))
                queue.append((nr,nc,d+1))
    raise RuntimeError("Maze is not connected")


def new_round(game, state, now):
    if game=="catch":
        state.update(lane=randbelow(3), start=now, ready=now+1.4, until=now+4.4)
    elif game=="reaction":
        ready=now+1.8+randbelow(1700)/1000
        state.update(start=now, ready=ready, until=ready+1.5)


def new_game(game, now):
    state = {"round":0,"points":0}
    if game in ("catch","reaction"):
        new_round(game,state,now)
    elif game=="memory":
        state.update(sequence=[randbelow(len(SYMBOLS)) for _ in range(6)], reveal_until=now+5)
    elif game=="maze":
        grid=maze_generate()
        state.update(grid=grid,row=1,col=1,moves=0,optimal=shortest_path(grid))
    return state


def public_state(game,state,now):
    result = dict(state)
    if game=="memory" and now>=state["reveal_until"]:
        result.pop("sequence",None)
    return result


def advance(game, state, move, now):
    """Return (message, accepted, finished, score). Invalid input leaves state intact."""
    if game=="catch":
        if type(move) is not int or move not in (-1,0,1,2):
            return "Выберите дорожку",False,False,0
        if now<state["ready"]:
            return "Предмет ещё летит",False,False,0
        if move==-1 and now<=state["until"]:
            return "Раунд ещё идёт",False,False,0
        hit=move==state["lane"] and now<=state["until"]
        state["points"]+=20 if hit else 0
        state["round"]+=1
        done=state["round"]>=5
        if not done:new_round(game,state,now)
        return ("Поймано! +20" if hit else "Мимо"),True,done,state["points"]
    if game=="reaction":
        if move!="tap":
            return "Нажмите сигнал",False,False,0
        elapsed=now-state["ready"]
        points=max(0,round(100*(1-elapsed/1.5))) if 0<=elapsed<=1.5 else 0
        state["points"]+=points
        state["round"]+=1
        done=state["round"]>=3
        if not done:new_round(game,state,now)
        return (f"Реакция: {points}/100" if points else "Слишком рано или поздно"),True,done,round(state["points"]/3)
    if game=="memory":
        if type(move) is not int or not 0<=move<len(SYMBOLS):
            return "Выберите символ",False,False,0
        if now<state["reveal_until"]:
            return "Сначала запомните последовательность",False,False,0
        correct=move==state["sequence"][state["round"]]
        state["points"]+=int(correct)
        state["round"]+=1
        return ("Верно!" if correct else "Не тот символ"),True,state["round"]>=6,round(state["points"]*100/6)
    if game=="maze":
        if not isinstance(move,str) or move not in DIRECTIONS:
            return "Выберите направление",False,False,0
        dr,dc=DIRECTIONS[move]
        r,c=state["row"]+dr,state["col"]+dc
        if not (0<=r<7 and 0<=c<7 and state["grid"][r][c]=="."):
            return "Здесь стена",False,False,0
        state.update(row=r,col=c,moves=state["moves"]+1)
        won=(r,c)==(5,5)
        done=won or state["moves"]>=MAX_MOVES
        score=round(100*state["optimal"]/state["moves"]) if won else 0
        return ("Выход найден!" if won else "Ход выполнен"),True,done,score
    return "Неизвестная игра",False,False,0


def arcade_config():
    return {"games":[{"code":code,**data} for code,data in GAMES.items()],
            "attempts":DAILY_ATTEMPTS,"rewards":DAILY_REWARDS,"reward_xp":REWARD_XP,
            "reward_score":REWARD_SCORE,"seconds":SESSION_SECONDS,
            "symbols":list(SYMBOLS),"max_moves":MAX_MOVES}
